//! # Laravel Build
//!
//! Convention over configuration, at compile time. Drop a migration into
//! `database/migrations`, a seeder into `database/seeders`, or a command into
//! `app/console/commands`, or a Blade component into `app/view/components`,
//! and it is discovered automatically — no registration required.
//!
//! Your application's `build.rs` is a single line:
//!
//! ```ignore
//! fn main() {
//!     laravel_build::discover();
//! }
//! ```
//!
//! and the matching modules include the generated code:
//!
//! ```ignore
//! // database/migrations/mod.rs
//! laravel::discover_migrations!();
//! ```

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// Discover every convention-based directory and generate the registries.
pub fn discover() {
    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is set by Cargo"));
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR is set by Cargo"));
    Discovery::new(manifest_dir, out_dir).run();
}

/// Generates registries for the conventional application directories.
pub struct Discovery {
    base: PathBuf,
    out: PathBuf,
    krate: String,
}

impl Discovery {
    /// Create a discovery rooted at the application's base path.
    pub fn new(base: impl Into<PathBuf>, out: impl Into<PathBuf>) -> Self {
        Self {
            base: base.into(),
            out: out.into(),
            krate: "::laravel".to_string(),
        }
    }

    /// Use a different path for the framework crate in generated code.
    pub fn framework_path(mut self, path: impl Into<String>) -> Self {
        self.krate = path.into();
        self
    }

    /// Generate every registry.
    pub fn run(&self) {
        let dir = self.out.join("laravel");
        std::fs::create_dir_all(&dir).expect("unable to create the generated code directory");

        let migrations = self.base.join("database/migrations");
        let seeders = self.base.join("database/seeders");
        let commands = self.base.join("app/console/commands");
        let components = self.base.join("app/view/components");
        let policies = self.base.join("app/policies");

        write(&dir.join("migrations.rs"), &self.migrations(&migrations));
        write(&dir.join("seeders.rs"), &self.seeders(&seeders));
        write(&dir.join("commands.rs"), &self.commands(&commands));
        write(&dir.join("components.rs"), &self.components(&components));
        write(&dir.join("policies.rs"), &self.policies(&policies));

        let mut watched = Vec::new();
        for path in [&migrations, &seeders, &commands, &components, &policies] {
            if let Some(path) = self.watched(path)
                && !watched.contains(&path)
            {
                println!("cargo:rerun-if-changed={}", path.display());
                watched.push(path);
            }
        }
        println!("cargo:rerun-if-changed=build.rs");
    }

    /// The directory to watch for changes to `dir`: the directory itself,
    /// or — until it exists — its nearest existing parent inside the
    /// application, so creating it reruns discovery. Cargo treats a missing
    /// path as always changed, which would rebuild the application on every
    /// `cargo artisan`; the application's root is never watched, since it
    /// holds `target`.
    fn watched<'a>(&self, dir: &'a Path) -> Option<&'a Path> {
        dir.ancestors()
            .take_while(|path| *path != self.base)
            .find(|path| path.is_dir())
    }

    /// The generated module for migrations.
    pub fn migrations(&self, dir: &Path) -> String {
        let files = rust_files(dir);
        let krate = &self.krate;
        let mut out = String::from("// Generated by laravel-build. Do not edit.\n\n");
        for (stem, path) in &files {
            let _ = writeln!(out, "#[path = {:?}]\nmod {};", path.display().to_string(), module_name("m", stem));
        }
        let _ = writeln!(
            out,
            "\n/// Every migration in `database/migrations`, ordered by name.\npub fn all() -> ::std::vec::Vec<(::std::string::String, ::std::boxed::Box<dyn {krate}::database::Migration>)> {{\n    ::std::vec!["
        );
        for (stem, _) in &files {
            let _ = writeln!(
                out,
                "        (::std::string::String::from({stem:?}), ::std::boxed::Box::new({}::{})),",
                module_name("m", stem),
                studly(strip_date_prefix(stem))
            );
        }
        out.push_str("    ]\n}\n");
        out
    }

    /// The generated module for seeders.
    pub fn seeders(&self, dir: &Path) -> String {
        let files = rust_files(dir);
        let krate = &self.krate;
        let mut out = String::from("// Generated by laravel-build. Do not edit.\n\n");
        for (stem, path) in &files {
            let _ = writeln!(
                out,
                "#[path = {:?}]\npub mod {stem};\npub use {stem}::{};",
                path.display().to_string(),
                studly(stem)
            );
        }
        let _ = writeln!(
            out,
            "\n/// Register every seeder in `database/seeders`.\npub fn register(registry: &{krate}::database::SeederRegistry) {{"
        );
        for (stem, _) in &files {
            let _ = writeln!(out, "    registry.register::<{}>();", studly(stem));
        }
        out.push_str("}\n");
        out
    }

    /// The generated module for Artisan commands.
    pub fn commands(&self, dir: &Path) -> String {
        let files = rust_files(dir);
        let krate = &self.krate;
        let mut out = String::from("// Generated by laravel-build. Do not edit.\n\n");
        for (stem, path) in &files {
            let _ = writeln!(
                out,
                "#[path = {:?}]\npub mod {stem};\npub use {stem}::{};",
                path.display().to_string(),
                studly(stem)
            );
        }
        let _ = writeln!(
            out,
            "\n/// Every command in `app/console/commands`.\npub fn all() -> ::std::vec::Vec<::std::boxed::Box<dyn {krate}::console::Command>> {{\n    ::std::vec!["
        );
        for (stem, _) in &files {
            let _ = writeln!(out, "        ::std::boxed::Box::new({}),", studly(stem));
        }
        out.push_str("    ]\n}\n");
        out
    }

    /// The generated module for Blade class components: `alert_banner.rs`
    /// defining `AlertBanner` becomes `<x-alert-banner>`.
    pub fn components(&self, dir: &Path) -> String {
        let files = rust_files(dir);
        let krate = &self.krate;
        let mut out = String::from("// Generated by laravel-build. Do not edit.\n\n");
        for (stem, path) in &files {
            let _ = writeln!(
                out,
                "#[path = {:?}]\npub mod {stem};\npub use {stem}::{};",
                path.display().to_string(),
                studly(stem)
            );
        }
        let _ = writeln!(
            out,
            "\n/// Register every component in `app/view/components` with Blade.\npub fn register(blade: &{krate}::view::BladeCompiler) {{"
        );
        for (stem, _) in &files {
            let _ = writeln!(out, "    blade.component({:?}, {}::new);", stem.replace('_', "-"), studly(stem));
        }
        if files.is_empty() {
            out.push_str("    let _ = blade;\n");
        }
        out.push_str("}\n");
        out
    }

    /// The generated module for policies. Like Laravel's policy discovery,
    /// `PostPolicy` (in `app/policies/post_policy.rs`) authorizes
    /// `crate::app::models::Post`.
    pub fn policies(&self, dir: &Path) -> String {
        let files = rust_files(dir);
        let krate = &self.krate;
        let mut out = String::from("// Generated by laravel-build. Do not edit.\n\n");
        for (stem, path) in &files {
            let _ = writeln!(
                out,
                "#[path = {:?}]\npub mod {stem};\npub use {stem}::{};",
                path.display().to_string(),
                studly(stem)
            );
        }
        out.push_str("\n/// Register every policy in `app/policies` with the gate.\npub fn register() {\n");
        for (stem, _) in &files {
            let policy = studly(stem);
            let Some(model) = policy.strip_suffix("Policy").filter(|model| !model.is_empty()) else {
                continue;
            };
            let _ = writeln!(
                out,
                "    {krate}::auth::Gate::policy::<crate::app::models::{model}, {policy}>(<{policy} as ::std::default::Default>::default());"
            );
        }
        out.push_str("}\n");
        out
    }
}

/// The `.rs` files in a directory (excluding `mod.rs`), sorted by name.
fn rust_files(dir: &Path) -> Vec<(String, PathBuf)> {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return Vec::new();
    };
    let mut files: Vec<(String, PathBuf)> = entries
        .filter_map(Result::ok)
        .map(|entry| entry.path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "rs"))
        .filter_map(|path| {
            let stem = path.file_stem()?.to_str()?.to_string();
            (stem != "mod").then_some((stem, path))
        })
        .collect();
    files.sort_by(|a, b| a.0.cmp(&b.0));
    files
}

/// Turn a file stem into a valid module name (they may start with digits).
fn module_name(prefix: &str, stem: &str) -> String {
    let cleaned: String = stem
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' })
        .collect();
    format!("{prefix}{cleaned}")
}

/// Strip a migration's `2024_01_01_000000_` timestamp prefix.
fn strip_date_prefix(stem: &str) -> &str {
    let bytes = stem.as_bytes();
    let pattern = [4, 2, 2, 6];
    let mut index = 0;
    for len in pattern {
        let segment = &bytes[index.min(bytes.len())..];
        if segment.len() <= len || !segment[..len].iter().all(u8::is_ascii_digit) || segment[len] != b'_' {
            return stem;
        }
        index += len + 1;
    }
    &stem[index..]
}

/// `create_users_table` => `CreateUsersTable`.
fn studly(value: &str) -> String {
    value
        .split(['_', '-'])
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

fn write(path: &Path, contents: &str) {
    // Only touch the file when it changes, so dependants don't rebuild needlessly.
    if std::fs::read_to_string(path).ok().as_deref() != Some(contents) {
        std::fs::write(path, contents).expect("unable to write generated code");
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn it_strips_migration_prefixes() {
        assert_eq!(strip_date_prefix("0001_01_01_000000_create_users_table"), "create_users_table");
        assert_eq!(strip_date_prefix("2024_03_12_153000_add_votes_to_users"), "add_votes_to_users");
        assert_eq!(strip_date_prefix("create_users_table"), "create_users_table");
    }

    #[test]
    fn it_builds_studly_names() {
        assert_eq!(studly("create_users_table"), "CreateUsersTable");
        assert_eq!(studly("database_seeder"), "DatabaseSeeder");
    }

    #[test]
    fn it_generates_migration_registries() {
        let dir = std::env::temp_dir().join(format!("laravel-build-test-{}", std::process::id()));
        let migrations = dir.join("database/migrations");
        std::fs::create_dir_all(&migrations).unwrap();
        std::fs::write(migrations.join("0001_01_01_000000_create_users_table.rs"), "").unwrap();
        std::fs::write(migrations.join("mod.rs"), "").unwrap();

        let generated = Discovery::new(&dir, &dir).migrations(&migrations);
        assert!(generated.contains("mod m0001_01_01_000000_create_users_table;"));
        assert!(generated.contains(
            "(::std::string::String::from(\"0001_01_01_000000_create_users_table\"), ::std::boxed::Box::new(m0001_01_01_000000_create_users_table::CreateUsersTable))"
        ));
        assert!(!generated.contains("mod mmod"));
        std::fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn it_discovers_components_and_policies() {
        let dir = std::env::temp_dir().join(format!("laravel-build-discovery-{}", std::process::id()));
        let components = dir.join("app/view/components");
        let policies = dir.join("app/policies");
        std::fs::create_dir_all(&components).unwrap();
        std::fs::create_dir_all(&policies).unwrap();
        std::fs::write(components.join("alert_banner.rs"), "").unwrap();
        std::fs::write(policies.join("post_policy.rs"), "").unwrap();
        std::fs::write(policies.join("helpers.rs"), "").unwrap();

        let discovery = Discovery::new(&dir, &dir);

        let generated = discovery.components(&components);
        assert!(generated.contains("pub use alert_banner::AlertBanner;"));
        assert!(generated.contains(r#"blade.component("alert-banner", AlertBanner::new);"#));

        let generated = discovery.policies(&policies);
        assert!(generated.contains("pub use post_policy::PostPolicy;"));
        assert!(generated.contains("Gate::policy::<crate::app::models::Post, PostPolicy>"));
        assert!(!generated.contains("Gate::policy::<crate::app::models::Helpers"));
        std::fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn it_watches_the_nearest_existing_directory() {
        let dir = std::env::temp_dir().join(format!("laravel-build-watched-{}", std::process::id()));
        let migrations = dir.join("database/migrations");
        std::fs::create_dir_all(&migrations).unwrap();
        std::fs::create_dir_all(dir.join("app")).unwrap();

        let discovery = Discovery::new(&dir, &dir);

        assert_eq!(discovery.watched(&migrations), Some(migrations.as_path()));
        let policies = dir.join("app/policies");
        assert_eq!(discovery.watched(&policies), Some(dir.join("app").as_path()));
        let commands = dir.join("app/console/commands");
        assert_eq!(discovery.watched(&commands), Some(dir.join("app").as_path()));
        assert_eq!(discovery.watched(&dir.join("missing/directory")), None);
        std::fs::remove_dir_all(&dir).ok();
    }
}
